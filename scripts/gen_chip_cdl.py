import re

core_cdl = '/mnt/g/VLSI_Projects/FIR2D_Filter_SCL1p2um/lvs/fir2d_core.cdl'
chip_cdl = '/mnt/g/VLSI_Projects/FIR2D_Filter_SCL1p2um/lvs/fir2d_chip_4mmx4mm.cdl'

with open(core_cdl, 'r') as f:
    core_text = f.read()

# Replace any missing dummy pin on CLKLOAD instances
core_clean = re.sub(r'(XCLKLOAD\d+\s+\S+\s+VDD\s+VSS\s+CDRI01)', r'\1_DUMMY', core_text)

# Build full chip CDL
full_chip_text = f"""* ==============================================================================
* SCL 1.2 um 2D FIR Filter Full Chip CDL Netlist
* ==============================================================================

.INCLUDE core_iolib_c1d.cdl
.INCLUDE io_pad_c1d.cdl

.GLOBAL VDD VSS

{core_clean}

.SUBCKT fir2d_chip_4mmx4mm PAD1 PAD2 PAD3 PAD4 PAD5 PAD6 PAD7 PAD8 PAD9 PAD10 PAD11 PAD12 PAD13 PAD14 PAD15 PAD16 PAD17 PAD18 PAD19 PAD20 PAD21 PAD22 PAD23 PAD24 PAD25 PAD26 PAD27 PAD28 PAD29 PAD30 PAD31 PAD32 VDD VSS

* Instantiate Core Block
XCORE CLK FRAME_DONE LINE_DONE RST_N VALID_IN VALID_OUT MODE[0] MODE[1] DIN[0] DIN[1] DIN[2] DIN[3] DIN[4] DIN[5] DIN[6] DIN[7] DOUT[0] DOUT[1] DOUT[2] DOUT[3] DOUT[4] DOUT[5] DOUT[6] DOUT[7] VDD VSS FIR2D_TOP

* Input Pads (IPAD20 / IPAD00)
X1  VSS PAD1  CLK        VDD IPAD20
X2  VSS PAD2  RST_N      VDD IPAD20
X3  VSS PAD3  VALID_IN   VDD IPAD20
X4  VSS PAD4  MODE[0]    VDD IPAD20
X5  VSS PAD5  MODE[1]    VDD IPAD20
X6  VSS PAD6  DIN[0]     VDD IPAD20
X7  VSS PAD7  DIN[1]     VDD IPAD20
X8  VSS PAD8  DIN[2]     VDD IPAD20
X9  VSS PAD9  DIN[3]     VDD IPAD20
X10 VSS PAD10 DIN[4]     VDD IPAD20
X11 VSS PAD11 DIN[5]     VDD IPAD20
X12 VSS PAD12 DIN[6]     VDD IPAD20
X13 VSS PAD13 DIN[7]     VDD IPAD20

* Output Pads (OPAD02 / OPAD04)
X14 VSS PAD14 DOUT[0]    VDD OPAD02
X15 VSS PAD15 DOUT[1]    VDD OPAD02
X16 VSS PAD16 DOUT[2]    VDD OPAD02
X17 VSS PAD17 DOUT[3]    VDD OPAD02
X18 VSS PAD18 DOUT[4]    VDD OPAD02
X19 VSS PAD19 DOUT[5]    VDD OPAD02
X20 VSS PAD20 DOUT[6]    VDD OPAD02
X21 VSS PAD21 DOUT[7]    VDD OPAD02
X22 VSS PAD22 VALID_OUT  VDD OPAD02
X23 VSS PAD23 LINE_DONE  VDD OPAD02
X24 VSS PAD24 FRAME_DONE VDD OPAD02

* Spare Pads
X25 VSS PAD25 SPARE25    VDD IPAD00
X26 VSS PAD26 SPARE26    VDD IPAD00
X27 VSS PAD27 SPARE27    VDD IPAD00
X28 VSS PAD28 SPARE28    VDD IPAD00
X29 VSS PAD29 SPARE29    VDD IPAD00
X30 VSS PAD30 SPARE30    VDD IPAD00
X31 VSS PAD31 SPARE31    VDD IPAD00
X32 VSS PAD32 SPARE32    VDD IPAD00

* Power and Ground Pads
XPVDD1 VDD VSS PVDD01
XPVSS1 VSS VDD PVSS01
XPVDD2 VDD VSS PVDD01
XPVSS2 VSS VDD PVSS01
XPVDD3 VDD VSS PVDD01
XPVSS3 VSS VDD PVSS01
XPVDD4 VDD VSS PVDD01
XPVSS4 VSS VDD PVSS01

.ENDS fir2d_chip_4mmx4mm
"""

with open(chip_cdl, 'w') as f:
    f.write(full_chip_text)

print(f"Full chip CDL written to {chip_cdl}")
